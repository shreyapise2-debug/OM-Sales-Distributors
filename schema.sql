-- OM Sales Distributors: PostgreSQL schema
-- Database: shreya_pise_om_sales
-- Create database separately in psql/pgAdmin, then connect to it before running this file.

CREATE TABLE suppliers (
    supplier_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_name VARCHAR(100) NOT NULL UNIQUE,
    contact_person VARCHAR(80) NOT NULL,
    phone VARCHAR(15) NOT NULL UNIQUE,
    email VARCHAR(120) UNIQUE,
    city VARCHAR(60) NOT NULL
);

CREATE TABLE products (
    product_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_name VARCHAR(120) NOT NULL,
    category VARCHAR(50) NOT NULL CHECK (category IN ('Skincare','Makeup','Haircare','Bodycare')),
    selling_price NUMERIC(10,2) NOT NULL CHECK (selling_price >= 0),
    stock_quantity INT NOT NULL DEFAULT 0 CHECK (stock_quantity >= 0),
    supplier_id INT NOT NULL REFERENCES suppliers(supplier_id) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE retailers (
    retailer_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    retailer_name VARCHAR(100) NOT NULL,
    contact_person VARCHAR(80) NOT NULL,
    phone VARCHAR(15) NOT NULL UNIQUE,
    email VARCHAR(120) UNIQUE,
    city VARCHAR(60) NOT NULL
);

CREATE TABLE sales_orders (
    order_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    retailer_id INT NOT NULL REFERENCES retailers(retailer_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    order_date DATE NOT NULL DEFAULT CURRENT_DATE,
    order_status VARCHAR(20) NOT NULL CHECK (order_status IN ('Pending','Processing','Dispatched','Delivered','Cancelled')),
    total_amount NUMERIC(12,2) NOT NULL CHECK (total_amount >= 0)
);

CREATE TABLE order_items (
    order_item_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id INT NOT NULL REFERENCES sales_orders(order_id) ON UPDATE CASCADE ON DELETE CASCADE,
    product_id INT NOT NULL REFERENCES products(product_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    quantity INT NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(10,2) NOT NULL CHECK (unit_price >= 0),
    line_total NUMERIC(12,2) GENERATED ALWAYS AS (quantity * unit_price) STORED
);

CREATE TABLE purchases (
    purchase_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id INT NOT NULL REFERENCES suppliers(supplier_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    product_id INT NOT NULL REFERENCES products(product_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    purchase_date DATE NOT NULL,
    quantity INT NOT NULL CHECK (quantity > 0),
    unit_cost NUMERIC(10,2) NOT NULL CHECK (unit_cost >= 0),
    purchase_status VARCHAR(20) NOT NULL CHECK (purchase_status IN ('Pending','In Transit','Received','Cancelled'))
);

CREATE INDEX idx_products_supplier ON products(supplier_id);
CREATE INDEX idx_orders_retailer ON sales_orders(retailer_id);
CREATE INDEX idx_order_items_order ON order_items(order_id);
CREATE INDEX idx_purchases_supplier ON purchases(supplier_id);
